"""Llasa TTS command-line interface."""

import asyncio

import click
from max import driver

from llasa.config import AudioType, LlasaConfig
from llasa.model import LlasaTTS
from llasa.prompt_template import create_llasa_prompt
from llasa.speech_lm import SpeechLM


def strip_repetitive_silence(
    tokens: list[int], silence_token: int = 42262, max_keep: int = 3
) -> list[int]:
    """Remove excessive repetitive silence tokens from the end.

    Args:
        tokens: List of speech tokens
        silence_token: The token ID representing silence (default `42262`)
        max_keep: Maximum number of silence tokens to keep at the end

    Returns:
        List with excessive silence stripped
    """
    if not tokens:
        return tokens

    end_idx = len(tokens)
    while end_idx > 0 and tokens[end_idx - 1] == silence_token:
        end_idx -= 1

    trailing_silence_count = len(tokens) - end_idx
    silence_to_keep = min(trailing_silence_count, max_keep)

    return tokens[: end_idx + silence_to_keep]


@click.command()
@click.option("--text", "-t", help="The text to convert to speech")
@click.option(
    "--format-prompt",
    is_flag=True,
    help="Formats the text prompt and shows tokenization",
)
@click.option(
    "--generate-tokens",
    is_flag=True,
    help="Generate speech tokens from text using Llama model",
)
@click.option(
    "--strip-silence",
    is_flag=True,
    help="Remove repetitive silence tokens from `--generate-tokens` output",
)
@click.option(
    "--print-raw-text",
    is_flag=True,
    help="Print the raw text generated by `--generate-tokens`",
)
@click.option(
    "--generate",
    is_flag=True,
    help="Generate complete audio file from text (end-to-end TTS)",
)
@click.option(
    "--output",
    "-o",
    default="generated_audio.wav",
    help="Output audio file path",
)
@click.option(
    "--audio-type",
    type=click.Choice(["white_noise", "sine_wave"]),
    default="white_noise",
    help="Type of stub audio to generate",
)
@click.help_option("--help", "-h")
def main(
    text: str,
    format_prompt: bool,
    generate_tokens: bool,
    strip_silence: bool,
    print_raw_text: bool,
    generate: bool,
    output: str,
    audio_type: str,
) -> None:
    """Llasa TTS - Text-to-Speech using Llama + XCodec2."""
    config = LlasaConfig()

    if (strip_silence or print_raw_text) and not generate_tokens:
        click.echo(
            "Error: --strip-silence and --print-raw-text can only be used with --generate-tokens"
        )
        return
    if (output or audio_type) and not generate:
        click.echo(
            "Error: --output and --audio-type can only be used with --generate"
        )
        return

    if format_prompt and text:
        input_ids, tokenizer = create_llasa_prompt(text, config)
        click.echo(f"Input text: {text}")
        click.echo(f"Formatted prompt tokens shape: {input_ids.shape}")
        click.echo(f"First few tokens: {input_ids[:10].tolist()}")
        click.echo(f"Tokenizer model: {config.llama_model_path}")
        return

    if generate_tokens and text:
        click.echo(f"Generating speech tokens for: '{text}'")

        device_specs = [driver.DeviceSpec(id=0, device_type="gpu")]
        speech_lm = SpeechLM(config, device_specs=device_specs)

        speech_tokens = asyncio.run(speech_lm.generate_speech_tokens(text))

        tokens_to_display = speech_tokens.tolist()
        if strip_silence:
            tokens_to_display = strip_repetitive_silence(tokens_to_display)
            click.echo(
                f"Generated {len(speech_tokens)} speech tokens ({len(tokens_to_display)} after stripping silence):"
            )
        else:
            click.echo(f"Generated {len(speech_tokens)} speech tokens:")

        click.echo(f"Speech tokens: {tokens_to_display}")

        if print_raw_text:
            raw_text = asyncio.run(speech_lm.generate_text_for_debugging(text))
            click.echo(f"Raw generated text: {raw_text}")
        return

    if generate and text:
        click.echo(f"Generating audio for: '{text}'")

        device_specs = [driver.DeviceSpec(id=0, device_type="gpu")]
        tts = LlasaTTS(config, device_specs=device_specs)

        audio_type_enum = AudioType(audio_type)

        try:
            output_path = asyncio.run(
                tts.generate_and_save(text, output, audio_type=audio_type_enum)
            )
            click.echo(f"Audio generated successfully: {output_path}")
        except Exception as e:
            click.echo(f"Error generating audio: {e}")
        return

    if not text:
        click.echo("No text provided!")
        return

    click.echo("Unknown command. Use --help for available options.")


if __name__ == "__main__":
    main()
